-- Run once in Supabase SQL Editor after verifying table backup.
-- Server-issued unique general membership IDs; separate from legacy users table.
-- Identity sequence is global per project (not reset per shop) and safe for concurrent signups.
ALTER TABLE public.membership_applications
  ADD COLUMN IF NOT EXISTS member_no bigint GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE public.membership_applications
  ADD COLUMN IF NOT EXISTS member_id text
    GENERATED ALWAYS AS ('M' || lpad(member_no::text, 6, '0')) STORED;
CREATE UNIQUE INDEX IF NOT EXISTS membership_applications_unique_member_no
  ON public.membership_applications(member_no);
CREATE UNIQUE INDEX IF NOT EXISTS membership_applications_unique_member_id
  ON public.membership_applications(member_id);
-- A NULL member_id means an old row wasn't backfilled; inspect existing rows before rollout.
SELECT id, shop_id, member_id, state FROM public.membership_applications ORDER BY requested_at DESC LIMIT 10;
